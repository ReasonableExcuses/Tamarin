static std::string_view trim(std::string_view s) {
    while (!s.empty() && std::isspace(static_cast<unsigned char>(s.front()))) {
        s.remove_prefix(1);
    }
    while (!s.empty() && std::isspace(static_cast<unsigned char>(s.back()))) {
        s.remove_suffix(1);
    }
    return s;
}

static std::string stripQuotes(std::string_view s) {
    s = trim(s);
    if (s.size() >= 2 && ((s.front() == '"' && s.back() == '"') || (s.front() == '\'' && s.back() == '\''))) {
        s.remove_prefix(1);
        s.remove_suffix(1);
    }
    return std::string(s);
}

static std::vector<std::string> parseArray(std::string_view s) {
    std::vector<std::string> out;
    s = trim(s);
    if (s.starts_with('[') && s.ends_with(']')) {
        s.remove_prefix(1);
        s.remove_suffix(1);
    }
    size_t start = 0;
    while (start < s.size()) {
        auto comma = s.find(',', start);
        std::string_view piece = (comma == std::string_view::npos) ? s.substr(start) : s.substr(start, comma - start);
        piece = trim(piece);
        if (!piece.empty()) {
            out.push_back(stripQuotes(piece));
        }
        if (comma == std::string_view::npos) break;
        start = comma + 1;
    }
    return out;
}

std::optional<Lockfile> Lockfile::loadFromFile(const std::filesystem::path& path, std::string& errorMsg) {
    std::ifstream file(path);
    if (!file.is_open()) {
        errorMsg = "cannot open lockfile: " + path.string();
        return std::nullopt;
    }
    std::stringstream buffer;
    buffer << file.rdbuf();
    return parseString(buffer.str(), errorMsg);
}

std::optional<Lockfile> Lockfile::parseString(std::string_view content, std::string& errorMsg) {
    (void)errorMsg;
    Lockfile lock;
    std::istringstream stream{std::string(content)};
    std::string line;
    LockedPackage* currentPkg = nullptr;
    bool inArray = false;
    std::string arrayBuf;

    while (std::getline(stream, line)) {
        std::string_view sv = trim(line);
        if (sv.starts_with('#') || sv.empty()) continue;

        if (inArray) {
            arrayBuf += " ";
            arrayBuf += sv;
            if (sv.find(']') != std::string_view::npos) {
                inArray = false;
                if (currentPkg) {
                    currentPkg->dependencies = parseArray(arrayBuf);
                }
                arrayBuf.clear();
            }
            continue;
        }

        if (sv == "[[package]]") {
            lock.packages.emplace_back();
            currentPkg = &lock.packages.back();
            continue;
        }

        auto eqPos = sv.find('=');
        if (eqPos == std::string_view::npos) continue;

        std::string key = std::string(trim(sv.substr(0, eqPos)));
        std::string_view rawVal = trim(sv.substr(eqPos + 1));

        if (key == "version" && currentPkg == nullptr) {
            lock.version = std::stoi(std::string(rawVal));
            continue;
        }

        if (currentPkg) {
            if (key == "name") {
                currentPkg->name = stripQuotes(rawVal);
            } else if (key == "version") {
                auto v = SemVer::parse(stripQuotes(rawVal));
                if (v) currentPkg->version = *v;
            } else if (key == "source") {
                currentPkg->source = stripQuotes(rawVal);
            } else if (key == "checksum") {
                currentPkg->checksum = stripQuotes(rawVal);
            } else if (key == "dependencies") {
                if (rawVal.starts_with('[') && !rawVal.ends_with(']')) {
                    inArray = true;
                    arrayBuf = std::string(rawVal);
                } else {
                    currentPkg->dependencies = parseArray(rawVal);
                }
            }
        }
    }

    return lock;
}

const LockedPackage* Lockfile::findPackage(const std::string& name) const {
    for (const auto& pkg : packages) {
        if (pkg.name == name) return &pkg;
    }
    return nullptr;
}

void Lockfile::addOrUpdatePackage(const LockedPackage& pkg) {
    for (auto& existing : packages) {
        if (existing.name == pkg.name) {
            existing = pkg;
            return;
        }
    }
    packages.push_back(pkg);
}

std::string Lockfile::toToml() const {
    std::ostringstream ss;
    ss << "# This file is automatically @generated by troop.\n";
    ss << "# It is not intended for manual editing.\n";
    ss << "version = " << version << "\n\n";

    for (const auto& pkg : packages) {
        ss << "[[package]]\n";
        ss << "name = \"" << pkg.name << "\"\n";
        ss << "version = \"" << pkg.version.toString() << "\"\n";
        if (!pkg.source.empty()) {
            ss << "source = \"" << pkg.source << "\"\n";
        }
        if (!pkg.checksum.empty()) {
            ss << "checksum = \"" << pkg.checksum << "\"\n";
        }
        if (!pkg.dependencies.empty()) {
            ss << "dependencies = [\n";
            for (const auto& dep : pkg.dependencies) {
                ss << "    \"" << dep << "\",\n";
            }
            ss << "]\n";
        }
        ss << "\n";
    }

    return ss.str();
}

bool Lockfile::saveToFile(const std::filesystem::path& path, std::string& errorMsg) const {
    std::ofstream file(path);
    if (!file.is_open()) {
        errorMsg = "cannot write lockfile: " + path.string();
        return false;
    }
    file << toToml();
    file.flush();
    if (!file.good()) {
        errorMsg = "failed to flush lockfile: " + path.string();
        return false;
    }
    return true;
}

std::string Lockfile::computeChecksum(const std::filesystem::path& path) {
    if (!std::filesystem::exists(path)) return "";

    uint64_t hash = 14695981039346656037ULL; // FNV-1a 64-bit offset basis
    const uint64_t fnvPrime = 1099511628211ULL;

    auto hashBuffer = [&](const uint8_t* data, size_t size) {
        for (size_t i = 0; i < size; ++i) {
            hash ^= data[i];
            hash *= fnvPrime;
        }
    };

    if (std::filesystem::is_regular_file(path)) {
        std::ifstream file(path, std::ios::binary);
        char buf[4096];
        while (file.read(buf, sizeof(buf)) || file.gcount() > 0) {
            hashBuffer(reinterpret_cast<const uint8_t*>(buf), static_cast<size_t>(file.gcount()));
        }
    } else if (std::filesystem::is_directory(path)) {
        std::vector<std::filesystem::path> files;
        for (const auto& entry : std::filesystem::recursive_directory_iterator(path)) {
            if (entry.is_regular_file()) {
                files.push_back(entry.path());
            }
        }
        std::sort(files.begin(), files.end());
        for (const auto& filePath : files) {
            std::string rel = std::filesystem::relative(filePath, path).generic_string();
            hashBuffer(reinterpret_cast<const uint8_t*>(rel.data()), rel.size());
            std::ifstream file(filePath, std::ios::binary);
            char buf[4096];
            while (file.read(buf, sizeof(buf)) || file.gcount() > 0) {
                hashBuffer(reinterpret_cast<const uint8_t*>(buf), static_cast<size_t>(file.gcount()));
            }
        }
    }

    std::ostringstream ss;
    ss << std::hex << std::setfill('0') << std::setw(16) << hash;
    return ss.str();
}

