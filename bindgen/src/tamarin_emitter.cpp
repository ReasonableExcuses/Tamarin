// ============================================================================
// tamarin_emitter.cpp - Code generator emitting Tamarin FFI definitions
// ============================================================================

#include "bindgen/tamarin_emitter.h"
#include <iomanip>

namespace tamarin::bindgen {

TamarinEmitter::TamarinEmitter(EmitterOptions options) : options_(std::move(options)) {}

std::string TamarinEmitter::transformName(const std::string& name) const {
    if (!options_.stripPrefix.empty() && name.starts_with(options_.stripPrefix)) {
        std::string stripped = name.substr(options_.stripPrefix.size());
        if (!stripped.empty()) return stripped;
    }
    return name;
}

std::string TamarinEmitter::transformType(const std::string& type) const {
    if (options_.stripPrefix.empty()) return type;
    // If type has prefix, replace it
    if (type.starts_with(options_.stripPrefix)) {
        return type.substr(options_.stripPrefix.size());
    }
    if (type.starts_with("*" + options_.stripPrefix)) {
        return "*" + type.substr(1 + options_.stripPrefix.size());
    }
    return type;
}

void TamarinEmitter::emit(const CHeaderModel& model, std::ostream& out) const {
    out << "// ============================================================================\n";
    out << "// Automatically generated by tamarin-bindgen\n";
    out << "// Source Header: " << model.headerPath << "\n";
    out << "// ============================================================================\n\n";

    if (!options_.moduleName.empty()) {
        out << "// Module: " << options_.moduleName << "\n\n";
    }

    bool isPub = options_.emitPublic || !options_.moduleName.empty();
    std::string pub = isPub ? "public " : "";

    // 1. Constants & Macros
    if (!model.constants.empty()) {
        out << "// ── Constants & Preprocessor Macros ────────────────────────────────────────\n";
        for (const auto& c : model.constants) {
            std::string tName = transformName(c.name);
            if (c.type == "string") {
                out << pub << "const u8[] " << tName << " = " << c.value << ";\n";
            } else if (c.type == "float") {
                out << pub << "const float " << tName << " = " << c.value << ";\n";
            } else if (c.type == "char") {
                out << pub << "const u8 " << tName << " = " << c.value << ";\n";
            } else if (c.type == "i64") {
                out << pub << "const i64 " << tName << " = " << c.value << ";\n";
            } else {
                out << pub << "const int " << tName << " = " << c.value << ";\n";
            }
        }
        out << "\n";
    }

    // 2. Enumerations
    if (!model.enums.empty()) {
        out << "// ── Enumerations ──────────────────────────────────────────────────────────\n";
        for (const auto& en : model.enums) {
            std::string eName = transformName(en.name);
            bool isSequential = !eName.empty();
            for (size_t i = 0; i < en.constants.size(); ++i) {
                if (en.constants[i].value != static_cast<int64_t>(i)) {
                    isSequential = false;
                    break;
                }
            }
            if (isSequential) {
                out << pub << "enum " << eName << " {\n";
                for (size_t i = 0; i < en.constants.size(); ++i) {
                    out << "    " << transformName(en.constants[i].name);
                    if (i + 1 < en.constants.size()) out << ",";
                    out << "\n";
                }
                out << "}\n\n";
            } else if (!eName.empty()) {
                out << "// enum " << eName << "\n";
            }
            for (const auto& c : en.constants) {
                out << pub << "const int " << transformName(c.name) << " = " << c.value << ";\n";
            }
            out << "\n";
        }
    }

    // 3. Structures and Unions
    if (!model.structs.empty()) {
        out << "// ── C-Compatible Structures ───────────────────────────────────────────────\n";
        for (const auto& st : model.structs) {
            std::string sName = transformName(st.name);
            if (st.isUnion) {
                out << "// C union: " << st.name << " (size: " << st.sizeInBytes << " bytes)\n";
                out << "@c_layout\n";
                out << pub << "struct " << sName << " {\n";
                int64_t sz = st.sizeInBytes > 0 ? st.sizeInBytes : 8;
                out << "    u8[" << sz << "] _raw;\n";
                out << "};\n\n";
                continue;
            }

            out << "@c_layout\n";
            out << pub << "struct " << sName << " {\n";
            if (st.fields.empty()) {
                int64_t sz = st.sizeInBytes > 0 ? st.sizeInBytes : 1;
                out << "    u8[" << sz << "] _opaque;\n";
            } else {
                for (const auto& f : st.fields) {
                    out << "    " << transformType(f.type.tamarinType) << " " << f.name << ";";
                    if (f.bitWidth >= 0) {
                        out << " // bitfield: " << f.bitWidth << " bits";
                    }
                    out << "\n";
                }
            }
            out << "};\n\n";
        }
    }

    // 4. Function Prototypes (extern "C")
    if (!model.functions.empty()) {
        out << "// ── C Foreign Function Declarations ───────────────────────────────────────\n";
        out << "extern \"C\" {\n";
        for (const auto& fn : model.functions) {
            std::string fName = fn.name; // Keep C linkage name intact for symbol resolution
            std::string retType = transformType(fn.returnType.tamarinType);
            out << "    " << pub << retType << " " << fName << "(";
            if (fn.params.empty()) {
                // In Tamarin, f() is empty parameter list
            } else {
                for (size_t i = 0; i < fn.params.size(); ++i) {
                    if (i > 0) out << ", ";
                    out << transformType(fn.params[i].type.tamarinType) << " " << fn.params[i].name;
                }
            }
            out << ");\n";
        }
        out << "}\n";
    }
}

} // namespace tamarin::bindgen
